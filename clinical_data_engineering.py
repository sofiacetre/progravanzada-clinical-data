#Cálculos estadísiticos
def ejecutar_pruebas_mann_whitney_y_holm(
    df_polars: pl.DataFrame, variables: list, col_objetivo: str = "Appendicitis_Binary"
) -> pd.DataFrame:

    resultados_crudos = []

    for variable in variables:
        grupo_0 = df_polars.filter(pl.col(col_objetivo) == 0)[variable].to_list()
        grupo_1 = df_polars.filter(pl.col(col_objetivo) == 1)[variable].to_list()

        prueba = mannwhitneyu(grupo_0, grupo_1, alternative="two-sided")
        u_stat = prueba.statistic
        p_val = prueba.pvalue

        n0, n1 = len(grupo_0), len(grupo_1)
        tamano_efecto = 1 - (2 * u_stat / (n0 * n1))

        resultados_crudos.append(
            {
                "variable": variable,
                "estadistico_U": u_stat,
                "p_original": p_val,
                "tamano_efecto": tamano_efecto,
            }
        )

    #Ordenar los valores de p para aplicar el ajuste de Holm
    resultados_ordenados = sorted(resultados_crudos, key=lambda x: x["p_original"])

    m = len(resultados_ordenados)

    for i, fila in enumerate(resultados_ordenados):
        p_ajustado = fila["p_original"] * (m - i)
        # Garantizamos monotonía (que ningún p ajustado sea menor al anterior)
        if i > 0 and p_ajustado < resultados_ordenados[i - 1]["p_ajustado_holm"]:
            p_ajustado = resultados_ordenados[i - 1]["p_ajustado_holm"]
        fila["p_ajustado_holm"] = min(p_ajustado, 1.0)
        fila["significativo_0_05"] = fila["p_ajustado_holm"] < 0.05

    return pd.DataFrame(resultados_ordenados)

#Entrenamiento de Modelos
def construir_y_entrenar_pipeline(
    X_train: pd.DataFrame, y_train: np.ndarray
) -> Pipeline:

    cols_numericas = X_train.select_dtypes(include=["int64", "float64"]).columns.tolist()
    cols_categoricas = X_train.select_dtypes(include=["object", "bool"]).columns.tolist()

    preprocesador = ColumnTransformer(
        transformers=[
            ("numericas", StandardScaler(), cols_numericas),
            (
                "categoricas",
                OneHotEncoder(handle_unknown="ignore"),
                cols_categoricas,
            ),
        ]
    )

    modelo = Pipeline(
        steps=[
            ("preprocesamiento", preprocesador),
            ("clasificador", LogisticRegression(max_iter=1000)),
        ]
    )

    modelo.fit(X_train, y_train)
    return modelo


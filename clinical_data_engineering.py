#Función para extraer info con BeautifulSoup
def extraer_seccion_medline(soup: BeautifulSoup, header_objetivo: str) -> str:
  #Buscar los encabezados y extraer unicamente los parrafos y las listas de estas secciones (h2/h3)
  objetivo_norm = header_objetivo.lower()

  encabezado = soup.find(
      lambda tag: tag.name in ["h2", "h3"]
      and (objetivo_norm in tag.get_text(" ", strip=True).lower()
          or "c-reactive" in tag.get_text(" ", strip=True).lower()
          and "what is" in tag.get_text(" ", strip=True).lower()
          and "crp" in objetivo_norm)
  )

  if not encabezado:
        # Respaldo: si la página cambia de estructura, extraemos los párrafos de <main>
        contenedor = soup.find("main") or soup
        return " ".join(
            p.get_text(" ", strip=True)
            for p in contenedor.find_all("p")
            if p.get_text(strip=True)
        )

  contenido = []

  for elemento in encabezado.find_all_next():
        # Nos detenemos en cuanto empieza la siguiente sección (otro h2 o h3)
        if elemento.name in ["h2", "h3"]:
            break
        if elemento.name in ["p", "li"]:
            texto = elemento.get_text(" ", strip=True)
            if texto:
                contenido.append(texto)

  return " ".join(contenido).strip()

#Construcción de diccionario de Medline
def construir_diccionario_clinico(paginas: list) -> pd.DataFrame:
    #Recorrer la pagina, extraer el titulo y la descripcion de cada una de las variables y lo vamos a poner en un df.
    registros = []

    for pagina in paginas:
        url = pagina["url"]
        response = requests.get(url, headers=HEADERS_HTTP, timeout=20)

        if response.status_code != 200:
            print(f"Error ({response.status_code}) al consultar: {url}")
            continue

        soup = BeautifulSoup(response.text, "html.parser")
        titulo_tag = soup.find("h1")
        titulo_limpio = titulo_tag.get_text(strip=True) if titulo_tag else ""

        descripcion_limpia = extraer_seccion_medline(soup, pagina["header_objetivo"])

        for codigo, nombre in pagina["variables"]:
            registros.append(
                {
                    "variable_code": codigo,
                    "variable_name": nombre,
                    "description": descripcion_limpia,
                    "source_title": titulo_limpio,
                    "source_url": url,
                    "retrieved_at": datetime.now().isoformat(),
                }
            )

    df_clinical = pd.DataFrame(registros)

    # Limpiamos espacios en blanco y descartamos descripciones vacías
    df_clinical["description"] = df_clinical["description"].str.strip()
    df_clinical = df_clinical[df_clinical["description"] != ""]

    print(f"Registros clínicos extraídos y limpios: {len(df_clinical)}")
    return df_clinical

